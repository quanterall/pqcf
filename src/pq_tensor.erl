%% Abstract-index tensor monomials (decision record SY2, phase 4): canonical forms under the tensors' slot symmetries,
%% the commutation of equal tensors and the renaming of dummy indices, and the counting of independent scalar
%% invariants.
%%
%% A monomial is [{Name, [Index]}]: an index (an atom) appearing twice is a dummy, contracted with an implicit metric
%% (the positions up and down are not distinguished); once, a free index. The canonical form is the least index string
%% over every element of the slot symmetry group (signs included) and every order of equal tensors, the dummies renamed
%% in the order they first appear: the canonical representative of the double coset that Butler and Portugal's
%% algorithm computes (L. R. U. Manssur, R. Portugal, B. F. Svaiter, Int. J. Mod. Phys. C 13 (2002) 859;
%% J. M. Martín-García's xPerm, arXiv:0803.0862, https://arxiv.org/abs/0803.0862), found here by exhaustive search,
%% which is exact and fast for products of up to about four Riemann tensors. A monomial equal to minus itself is 0.
-module(pq_tensor).
-export([canonical/2, symmetries/0, full_contractions/2, independent_invariants/3]).

%% the slot symmetries: Name => [{Permutation of slots (1-based images), Sign}], the whole group
-spec symmetries() -> map().
symmetries() ->
    #{riemann => group([{[2, 1, 3, 4], -1}, {[1, 2, 4, 3], -1}, {[3, 4, 1, 2], 1}], 4),
      ricci => group([{[2, 1], 1}], 2),
      metric => group([{[2, 1], 1}], 2)}.

%% the group generated by Gens (closure)
group(Gens, N) -> closure([{lists:seq(1, N), 1}], Gens).

closure(Elems, Gens) ->
    New = lists:usort([compose(E, G) || E <- Elems, G <- Gens] ++ Elems),
    case length(New) =:= length(Elems) of
        true -> New;
        false -> closure(New, Gens)
    end.

%% slot i of the result takes slot P(i) of the input: (P o Q)(i) = Q(P(i))
compose({P, S1}, {Q, S2}) -> {[lists:nth(I, Q) || I <- P], S1 * S2}.

%% the canonical form of Coef * Monomial: {Coef2, Monomial2}, or 0
-spec canonical(integer() | {integer(), pos_integer()}, [{atom(), [atom()]}]) -> {term(), [{atom(), [atom()]}]} | 0.
canonical(Coef, Mono) ->
    Syms = symmetries(),
    Counts = lists:foldl(fun({_, Ix}, Acc) -> lists:foldl(fun(I, A) -> A#{I => maps:get(I, A, 0) + 1} end, Acc, Ix) end, #{}, Mono),
    lists:all(fun(C) -> C =< 2 end, maps:values(Counts)) orelse error({pq_tensor, index_more_than_twice}),
    {Best, Signs, _} = orbit(Mono, Counts, Syms),
    case Signs of
        [S] -> {mul_coef(S, Coef), Best};
        _ -> 0                                   % both signs: the monomial is its own negative
    end.

%% the least key, its signs, and every key of the orbit
orbit(Mono, Counts, Syms) ->
    Candidates = [{key(Arr, Counts), Sign}
                  || Order <- orders(lists:sort(Mono)), {Arr, Sign} <- slot_choices(Order, Syms)],
    Best = lists:min([K || {K, _} <- Candidates]),
    {Best, lists:usort([S || {K, S} <- Candidates, K =:= Best]), [K || {K, _} <- Candidates]}.

mul_coef(1, C) -> C;
mul_coef(-1, C) when is_integer(C) -> -C;
mul_coef(-1, {N, D}) -> {-N, D}.

%% every order of the factors that keeps equal names together in name order: the permutations within each name
orders(Sorted) ->
    Groups = group_by_name(Sorted),
    lists:foldl(fun(G, Acc) -> [A ++ P || A <- Acc, P <- perms(G)] end, [[]], Groups).

group_by_name([]) -> [];
group_by_name([{N, _} | _] = L) ->
    {Same, Rest} = lists:splitwith(fun({M, _}) -> M =:= N end, L),
    [Same | group_by_name(Rest)].

perms([]) -> [[]];
perms(L) -> [[H | T] || H <- L, T <- perms(L -- [H])].

%% every choice of a slot-group element per factor: {Factors with their indices permuted, Sign}
slot_choices(Order, Syms) ->
    lists:foldl(fun({Name, Ix}, Acc) ->
                        G = maps:get(Name, Syms, [{lists:seq(1, length(Ix)), 1}]),
                        [{Fs ++ [{Name, [lists:nth(I, Ix) || I <- P]}], S * Sg} || {Fs, S} <- Acc, {P, Sg} <- G]
                end, [{[], 1}], Order).

%% the dummies renamed '$1', '$2', ... in order of first appearance; free indices kept
key(Factors, Counts) ->
    {Out, _} = lists:mapfoldl(fun({Name, Ix}, Map0) ->
                                      {Ix2, Map2} = lists:mapfoldl(fun(I, M) ->
                                                                           case maps:get(I, Counts) of
                                                                               1 -> {I, M};
                                                                               2 ->
                                                                                   case maps:find(I, M) of
                                                                                       {ok, D} -> {D, M};
                                                                                       error -> D = {d, map_size(M) + 1}, {D, M#{I => D}}
                                                                                   end
                                                                           end
                                                                   end, Map0, Ix),
                                      {{Name, Ix2}, Map2}
                              end, #{}, Factors),
    Out.

%% every full contraction of K tensors Name (each with Slots slots), canonical, distinct, nonzero
-spec full_contractions(atom(), pos_integer()) -> [[{atom(), list()}]].
full_contractions(Name, K) ->
    Slots = case Name of riemann -> 4; ricci -> 2 end,
    N = K * Slots,
    Ms = matchings(lists:seq(1, N)),
    Monos = [begin
                 Label = maps:from_list(lists:append([[{A, list_to_atom("i" ++ integer_to_list(J))}, {B, list_to_atom("i" ++ integer_to_list(J))}]
                                                      || {J, {A, B}} <- lists:enumerate(M)])),
                 [{Name, [maps:get((T - 1) * Slots + S, Label) || S <- lists:seq(1, Slots)]} || T <- lists:seq(1, K)]
             end || M <- Ms],
    % each matching's orbit is recorded, so only one matching per class is canonicalised
    Syms = symmetries(),
    {Classes, _} = lists:foldl(
                     fun(M, {Acc, Seen}) ->
                             Counts = maps:from_list([{I, 2} || {_, Ix} <- M, I <- Ix]),
                             Raw = key(lists:sort(M), Counts),
                             case sets:is_element(Raw, Seen) of
                                 true -> {Acc, Seen};
                                 false ->
                                     {Best, Signs, Keys} = orbit(M, Counts, Syms),
                                     Seen2 = lists:foldl(fun sets:add_element/2, Seen, Keys),
                                     case Signs of [_] -> {[Best | Acc], Seen2}; _ -> {Acc, Seen2} end
                             end
                     end, {[], sets:new([{version, 2}])}, Monos),
    lists:usort(Classes).

matchings([]) -> [[]];
matchings([A | Rest]) -> [[{A, B} | M] || B <- Rest, M <- matchings(Rest -- [B])].

%% the number of linearly independent invariants among Monos, every index contracted: their values on Samples random
%% algebraic curvature tensors in dimension Dim (sums of Kulkarni-Nomizu squares of random integer symmetric matrices,
%% which satisfy every identity of the Riemann tensor, the cyclic one included), the rank of the integer matrix
-spec independent_invariants([[{atom(), list()}]], pos_integer(), pos_integer()) -> non_neg_integer().
independent_invariants(Monos, Dim, Samples) ->
    Rng0 = rand:seed_s(exsss, {Dim, Samples, length(Monos)}),
    {Rows, _} = lists:mapfoldl(fun(_, R0) ->
                                       {T, R1} = random_curvature(Dim, R0),
                                       {[value(M, T, Dim) || M <- Monos], R1}
                               end, Rng0, lists:seq(1, Samples)),
    rank(Rows).

random_curvature(Dim, R0) ->
    {Hs, R1} = lists:mapfoldl(fun(_, R) -> sym_matrix(Dim, R) end, R0, lists:seq(1, 3)),
    Ix = lists:seq(1, Dim),
    T = maps:from_list([{{A, B, C, D}, lists:sum([kn(H, A, B, C, D) || H <- Hs])} || A <- Ix, B <- Ix, C <- Ix, D <- Ix]),
    {T, R1}.

%% (h KN h)_abcd = 2 (h_ac h_bd - h_ad h_bc)
kn(H, A, B, C, D) -> 2 * (maps:get({A, C}, H) * maps:get({B, D}, H) - maps:get({A, D}, H) * maps:get({B, C}, H)).

sym_matrix(Dim, R0) ->
    Ps = [{I, J} || I <- lists:seq(1, Dim), J <- lists:seq(I, Dim)],
    {Vs, R1} = lists:mapfoldl(fun(_, R) -> {V, R2} = rand:uniform_s(11, R), {V - 6, R2} end, R0, Ps),
    M = maps:from_list(lists:append([[{{I, J}, V}, {{J, I}, V}] || {{I, J}, V} <- lists:zip(Ps, Vs)])),
    {M, R1}.

%% a full contraction's value: the sum over the dummies' values (Euclidean metric)
value(Mono, T, Dim) ->
    Dummies = lists:usort([I || {_, Ix} <- Mono, I <- Ix]),
    Assign = assignments(Dummies, Dim),
    lists:sum([lists:foldl(fun({_, Ix}, P) -> P * maps:get(list_to_tuple([maps:get(I, A) || I <- Ix]), T) end, 1, Mono)
               || A <- Assign]).

assignments([], _) -> [#{}];
assignments([D | Ds], Dim) -> [A#{D => V} || A <- assignments(Ds, Dim), V <- lists:seq(1, Dim)].

%% the rank of an integer matrix (fraction-free elimination, rows reduced by their gcd)
rank(Rows) -> rank(Rows, 0).

rank(Rows, R) ->
    case [Row || Row <- Rows, lists:any(fun(X) -> X =/= 0 end, Row)] of
        [] -> R;
        Nz ->
            Col = lists:min([length(lists:takewhile(fun(X) -> X =:= 0 end, Row)) || Row <- Nz]),
            {[P | With], Without} = lists:partition(fun(Row) -> lists:nth(Col + 1, Row) =/= 0 end, Nz),
            Pc = lists:nth(Col + 1, P),
            Red = [prim([Pc * X - lists:nth(Col + 1, Row) * Y || {X, Y} <- lists:zip(Row, P)]) || Row <- With] ++ Without,
            rank(Red, R + 1)
    end.

prim(Row) ->
    case lists:foldl(fun(X, G) -> gcd(abs(X), G) end, 0, Row) of
        0 -> Row;
        G -> [X div G || X <- Row]
    end.

gcd(A, 0) -> A;
gcd(A, B) -> gcd(B, A rem B).
